"""Generate frontend/src/types.ts from core.contract (the TypeScript mirror of the Case JSON contract).

Run after ANY change to core/contract.py (plan §16: contract, fixtures and TS types change together):

    uv run python scripts/gen_types_ts.py          # rewrites frontend/src/types.ts
    uv run python scripts/gen_types_ts.py --check  # exit 1 if the file is stale

tests/test_contract.py checks the mirror field for field (optionality included) and every enum union.
"""

from __future__ import annotations

import argparse
import sys
import types
import typing
from pathlib import Path
from typing import Annotated, Any, Literal, Union, get_args, get_origin

from pydantic import BaseModel

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from core import contract  # noqa: E402

OUT = REPO / "frontend" / "src" / "types.ts"
ENUM_BY_ARGS = {tuple(get_args(lit)): name for name, lit in contract.ENUMS.items()}


def ts_type(tp: Any) -> str:
    origin = get_origin(tp)
    if origin is Annotated:
        return ts_type(get_args(tp)[0])
    if origin is Literal:
        args = tuple(get_args(tp))
        if args in ENUM_BY_ARGS:
            return ENUM_BY_ARGS[args]
        return " | ".join(f'"{a}"' if isinstance(a, str) else str(a).lower() for a in args)
    if origin in (Union, types.UnionType):
        parts = [ts_type(a) for a in get_args(tp) if a is not type(None)]
        nullable = any(a is type(None) for a in get_args(tp))
        return " | ".join(parts + (["null"] if nullable else []))
    if origin in (list, typing.List):
        inner = ts_type(get_args(tp)[0])
        return f"({inner})[]" if " " in inner else f"{inner}[]"
    if origin in (tuple, typing.Tuple):
        return "[" + ", ".join(ts_type(a) for a in get_args(tp)) + "]"
    if origin in (dict, typing.Dict):
        key, value = get_args(tp)
        key_ts = ts_type(key)
        if key_ts in contract.ENUMS:
            return f"Partial<Record<{key_ts}, {ts_type(value)}>>"
        return f"Record<string, {ts_type(value)}>"
    if isinstance(tp, type) and issubclass(tp, BaseModel):
        return tp.__name__
    if tp is str:
        return "string"
    if tp in (int, float):
        return "number"
    if tp is bool:
        return "boolean"
    if tp is Any:
        return "unknown"
    raise TypeError(f"no TypeScript mapping for {tp!r}")


def render() -> str:
    out = [
        "// GENERATED by scripts/gen_types_ts.py from core/contract.py. Do not edit by hand.",
        "// TypeScript mirror of the PathQueue Case JSON contract (plan §7 + CELLS_SPEC §7.2 + BUILD_PLAN §A13).",
        "// The API returns CasePublic (never eval_only). Research prototype: not for clinical use.",
        "",
        f'export const SCHEMA_VERSION = "{contract.SCHEMA_VERSION}";',
        "",
    ]
    for name, lit in contract.ENUMS.items():
        out.append(f"export type {name} = " + " | ".join(f'"{a}"' for a in get_args(lit)) + ";")
    out.append("")
    for model in contract.PUBLIC_MODELS:
        out.append(f"export interface {model.__name__} {{")
        hints = typing.get_type_hints(model, include_extras=True)
        for field_name, field in model.model_fields.items():
            optional = "" if field.is_required() else "?"
            out.append(f"  {field_name}{optional}: {ts_type(hints[field_name])};")
        out.append("}")
        out.append("")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if frontend/src/types.ts is stale")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(REPO)} is stale; run scripts/gen_types_ts.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
